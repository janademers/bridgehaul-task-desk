import ts from 'typescript';
import fs from 'node:fs';
import assert from 'node:assert/strict';
let source=ts.transpileModule(fs.readFileSync('app/lib/recurrence.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
let {period,roll,dueDate,nextReset,currentPeriod,today}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(period('2026-11-17','Weekly'),'2026-11-16');
let weekly={active:true,frequency:'Weekly',schedule:'M',cycle:'2026-11-16',due:'2026-11-16',status:'Completed',lastCompleted:'2026-11-16'};
assert.equal(roll({...weekly},'2026-11-22').status,'Completed');
assert.equal(roll({...weekly},'2026-11-23').status,'Not Started');
assert.equal(roll({...weekly},'2026-11-23').lastCompleted,'2026-11-16');
assert.equal(roll({...weekly,status:'In Progress'},'2026-11-23').cycle,'2026-11-16');
assert.equal(roll({...weekly,status:'In Progress'},'2026-11-23').due,'2026-11-16');
assert.equal(currentPeriod({frequency:'Daily'},'2026-11-22'),'2026-11-20');
assert.equal(nextReset({frequency:'Daily',cycle:'2026-11-20'}),'2026-11-23');
assert.equal(nextReset({frequency:'Monthly',cycle:'2026-12-01'}),'2027-01-01');
assert.equal(dueDate({frequency:'Monthly',schedule:'BOM'},'2026-11-01'),'2026-11-02');
assert.equal(dueDate({frequency:'Monthly',schedule:'EOM'},'2028-02-01'),'2028-02-29');
assert.equal(today(new Date('2026-11-18T03:00:00Z')),'2026-11-17');
assert.equal(roll({active:true,frequency:'Weekly',schedule:'M',status:'Completed',lastCompleted:'2026-11-09'},'2026-11-17').status,'Not Started');
console.log('13 recurrence assertions passed.');
